const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
let chromium;
try { ({chromium} = require('playwright')); } catch {}
const executablePath = process.env.CHAT_TEST_BROWSER_PATH || chromium?.executablePath();

test('command editor builds branches, preserves drafts, tests without saving and recovers failed saves', {skip:!chromium || !fs.existsSync(executablePath || '')}, async()=>{
    const browser = await chromium.launch({executablePath, headless:true, args:['--no-sandbox']});
    try {
        const page = await browser.newPage({viewport:{width:1280,height:1000}});
        const errors=[];page.on('pageerror',e=>errors.push(e.message));
        const calls=[],payloads=[];let failSave=true;
        await page.route('http://editor.test/**',async route=>{
            if(route.request().url().endsWith('/commands/counters'))return route.fulfill({json:{counters:{wins:9}}});
            if(!route.request().url().endsWith('/commands'))return route.fulfill({body:'<html></html>',contentType:'text/html'});
            const data=new URLSearchParams(route.request().postData()||'');calls.push(data.get('action')||'list');if(data.get('action')==='save')payloads.push(Object.fromEntries(data));
            if(route.request().method()==='GET')return route.fulfill({json:{items:[]}});
            if(data.get('action')==='test')return route.fulfill({json:{messages:['Welcome Guest!'],trace:['has_argument: True','Send message']}});
            if(failSave){failSave=false;return route.fulfill({status:409,json:{detail:'Reload before saving.'}});}
            return route.fulfill({json:{revision:1}});
        });
        await page.goto('http://editor.test/channel/for-you');
        await page.setContent(`<body><main style="max-width:1100px;margin:40px auto;padding:20px"><h2>For You</h2><div data-workspace-page data-csrf="secret"><button data-workspace-tab="commands">Custom Commands</button>${fs.readFileSync('web/templates/channel/command_editor.html','utf8')}</div></main></body>`);
        for(const path of ['web/static/css/style.css','web/static/css/command-editor.css'])await page.addStyleTag({path});
        await page.addScriptTag({path:'web/static/js/command-canvas-model.js'});
        await page.addScriptTag({path:'web/static/js/command-editor.js'});
        await page.getByRole('button',{name:'Custom Commands',exact:true}).click();
        await page.getByRole('button',{name:'+ Add command',exact:true}).click();
        await page.getByLabel('Command name (without !)').fill('welcome');
        await page.getByLabel('Message',{exact:true}).fill('Hello {user}');
        await page.getByRole('button',{name:'Refresh counters',exact:true}).click();
        await page.getByText('Saved values refreshed.',{exact:true}).waitFor();
        assert.equal(await page.locator('.cc-counter-value').textContent(),'9');
        assert.equal(await page.getByLabel('Command name (without !)').inputValue(),'welcome');
        assert.equal(await page.getByLabel('Message',{exact:true}).inputValue(),'Hello {user}');

        assert.equal(await page.getByRole('button',{name:'+ Repeat',exact:true}).count(),0);
        await page.getByRole('button',{name:'+ Counter',exact:true}).click();
        await page.getByLabel('Counter name',{exact:true}).fill('wins');
        await page.getByLabel('Operation',{exact:true}).selectOption('set');
        await page.getByLabel('Value',{exact:true}).fill('4');
        const counterNode=page.getByRole('button',{name:'Counter 2',exact:true});
        await counterNode.click({button:'right'});
        await page.getByRole('menuitem',{name:'Delete',exact:true}).click();
        await page.getByRole('button',{name:'+ Random Number',exact:true}).click();
        await page.getByLabel('Result name',{exact:true}).fill('dice');
        await page.getByLabel('Minimum',{exact:true}).fill('1');
        await page.getByLabel('Maximum',{exact:true}).fill('6');
        await page.getByRole('button',{name:'Send message 1',exact:true}).click();
        assert.equal(await page.getByLabel('Insert a value').locator('option[value="random.dice"]').count(),0);
        await page.getByRole('button',{name:'Random Number 2',exact:true}).click({button:'right'});
        await page.getByRole('menuitem',{name:'Delete',exact:true}).click();
        const firstNode=page.getByRole('button',{name:'Send message 1',exact:true});
        await firstNode.click({button:'right'});
        await page.getByRole('menuitem',{name:'Copy',exact:true}).click();
        await firstNode.focus();await page.keyboard.press('Shift+F10');
        await page.getByRole('menuitem',{name:'Duplicate',exact:true}).click();
        assert.equal(await page.locator('.cc-node').count(),2);
        await page.getByRole('button',{name:'Send message 2',exact:true}).click({button:'right'});
        await page.getByRole('menuitem',{name:'Delete',exact:true}).click();
        assert.equal(await page.locator('.cc-node').count(),1);
        await firstNode.click({button:'right'});await page.keyboard.press('Escape');
        assert.equal(await page.getByRole('menu').count(),0);
        assert.equal(await page.getByLabel('Channel cooldown (seconds)').inputValue(),'0');
        await page.getByRole('button',{name:'+ If / else',exact:true}).click();
        await page.getByRole('button',{name:'True +',exact:true}).click();
        await page.getByRole('button',{name:'+ Send message',exact:true}).click();
        await page.getByLabel('Message',{exact:true}).fill('Welcome {arg1}!');
        assert.equal(await page.locator('.cc-node').count(),3);
        assert.equal(await page.getByLabel('Message',{exact:true}).count(),1);
        await page.getByLabel('Test arguments').fill('Guest');
        await page.getByRole('button',{name:'Run test',exact:true}).click();
        await page.getByText('Welcome Guest!',{exact:true}).waitFor();
        assert.deepEqual(calls,['list','test']);
        await page.getByRole('button',{name:'Full screen',exact:true}).click();
        assert.equal(await page.locator('.cc-expanded').count(),1);
        assert.equal(await page.getByText('Command sandbox',{exact:true}).count(),1);
        const columns=await page.locator('.cc-studio').evaluate(n=>getComputedStyle(n).gridTemplateColumns.split(' ').length);
        assert.equal(columns,3);
        assert.equal(await page.getByLabel('Test arguments').inputValue(),'Guest');
        await page.keyboard.press('Escape');assert.equal(await page.locator('.cc-expanded').count(),0);
        await page.getByRole('button',{name:'Save',exact:true}).click();
        await page.getByText('Reload before saving.',{exact:true}).first().waitFor();
        assert.equal(await page.getByLabel('Command name (without !)').inputValue(),'welcome');
        page.once('dialog',dialog=>dialog.dismiss());
        await page.getByRole('button',{name:'Cancel',exact:true}).click();
        assert.equal(await page.locator('.cc-editor').count(),1);
        if(process.env.COMMAND_EDITOR_SCREENSHOT)await page.screenshot({path:process.env.COMMAND_EDITOR_SCREENSHOT,fullPage:true});
        await page.getByRole('button',{name:'Save',exact:true}).click();
        await page.getByText('Command saved.',{exact:true}).waitFor();
        assert.equal(await page.locator('.cc-editor').count(),0);
        assert.equal(await page.getByRole('switch').getAttribute('aria-checked'),'false');
        await page.getByRole('button',{name:'Edit',exact:true}).click();
        assert.equal(await page.getByLabel('Command name (without !)').isDisabled(),false);
        await page.getByLabel('Command name (without !)').fill('renamed');
        await page.getByRole('switch').click();
        assert.equal(await page.getByRole('switch').getAttribute('aria-checked'),'true');
        // Layout changes are saved independently from sequence order.
        const node=page.getByRole('button',{name:'Send message 1',exact:true});
        await node.scrollIntoViewIfNeeded();
        const before=await node.evaluate(n=>({x:parseFloat(n.style.left),y:parseFloat(n.style.top)}));
        const box=await node.boundingBox();
        await page.mouse.move(box.x+30,box.y+25);await page.mouse.down();
        await page.mouse.move(box.x+130,box.y+45,{steps:10});await page.mouse.up();
        await page.getByRole('button',{name:'Save',exact:true}).click();
        await page.getByText('Command saved.',{exact:true}).waitFor();
        const saved=payloads.at(-1),definition=JSON.parse(saved.definition);
        assert.equal(saved.original_name,'welcome');assert.equal(definition.name,'renamed');
        assert.equal(definition.cooldown,0);assert.equal(definition.enabled,true);
        assert.equal(definition.blocks[0].message,'Hello {user}');
        assert.ok(definition.blocks[0].position.x>before.x);
        assert.ok(definition.blocks[0].position.y>before.y);
        assert.equal(definition.blocks[1].then[0].message,'Welcome {arg1}!');
        assert.deepEqual(errors,[]);
    } finally {await browser.close();}
});
